// Builds openings.js, the review's opening book, from lichess's openings list (CC0,
// https://github.com/lichess-org/chess-openings). Every position along every named line is stored
// as a 32-bit hash of its piece placement, side to move and castling rights, so a move is "book"
// when it reaches one of those positions, whatever the move order.
// Usage: node make-openings.js   (downloads a.tsv … e.tsv; needs an internet connection)
const fs = require('fs');
const path = require('path');
const E = require('./engine.js');
const OB = require('./openings-core.js');

(async () => {
  const set = new Set();
  let lines = 0;
  for (const f of 'abcde') {
    const res = await fetch(`https://raw.githubusercontent.com/lichess-org/chess-openings/master/${f}.tsv`);
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${f}.tsv`);
    for (const row of (await res.text()).trim().split('\n').slice(1)) {
      let g = E.newGame();
      for (const m of E.parsePGN(row.split('\t')[2]).moves) { g = E.makeMove(g, m); set.add(OB.hash(E.toFEN(g))); }
      lines++;
    }
  }
  const codes = [...set].sort((a, b) => a - b).map((h) => h.toString(36)).join(',');
  fs.writeFileSync(path.join(__dirname, 'openings.js'),
    `// Generated by make-openings.js from lichess's openings list (CC0): ${lines} lines, ${set.size} positions.\n` +
    `(function (root) { root.OPENING_CODES = '${codes}'; })(typeof window !== 'undefined' ? window : globalThis);\n` +
    `if (typeof module !== 'undefined' && module.exports) module.exports = globalThis.OPENING_CODES;\n`);
  console.log(`${lines} lines, ${set.size} positions`);
})();
